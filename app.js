function initClusterView() {
  const container = document.getElementById('cluster-cards-container');
  container.innerHTML = '';

  CLUSTER_DATA.cluster_list.forEach((cl, idx) => {
    const card = document.createElement('div');
    card.className = `cluster-btn-card ${idx === 2 ? 'active' : ''}`;
    card.id = `btn-cl-${cl.id}`;
    card.style.borderTop = `3px solid ${cl.color}`;
    card.onclick = () => selectCluster(cl.id);

    card.innerHTML = `
      <div class="cl-head">
        <span class="cl-name" style="color:${cl.color}">${cl.name}</span>
        <span class="cl-badge" style="background:${cl.color}22; color:${cl.color}">${cl.badge}</span>
      </div>
      <div class="cl-desc" style="font-size:11px; color:#94a3b8; height:32px; overflow:hidden;">${cl.desc}</div>
      <div class="cl-metrics">
        <div class="cl-metric-item">고객 <strong>${cl.count.toLocaleString()}명</strong></div>
        <div class="cl-metric-item">할인율 <strong>${cl.avg_discount_rate}%</strong></div>
        <div class="cl-metric-item">객단가 <strong>${Math.round(cl.avg_aov / 1000)}천원</strong></div>
      </div>
    `;
    container.appendChild(card);
  });

  setTimeout(() => selectCluster('cherrypicker'), 100);
}

function selectCluster(clusterId) {
  activeClusterId = clusterId;

  document.querySelectorAll('.cluster-btn-card').forEach(c => c.classList.remove('active'));
  const targetCard = document.getElementById(`btn-cl-${clusterId}`);
  if (targetCard) targetCard.classList.add('active');

  const meta = CLUSTER_DATA.cluster_list.find(c => c.id === clusterId);
  const details = CLUSTER_DATA.cluster_details[clusterId];

  document.getElementById('action-name').textContent = meta.name;
  document.getElementById('action-name').style.color = meta.color;
  document.getElementById('action-badge').textContent = meta.badge;
  document.getElementById('action-badge').style.background = `${meta.color}22`;
  document.getElementById('action-badge').style.color = meta.color;
  document.getElementById('action-desc').textContent = meta.desc;

  document.getElementById('m-count').textContent = `${meta.count.toLocaleString()}명 (${(meta.count/100).toFixed(1)}%)`;
  document.getElementById('m-disc').textContent = `${meta.avg_discount_rate}%`;
  document.getElementById('m-spend').textContent = `${Math.round(meta.avg_spend / 10000)}만원`;
  document.getElementById('m-freq').textContent = `${meta.avg_freq}회`;

  document.getElementById('strategy-banner').innerHTML = `<strong>🎯 데이터 기반 실행 전략:</strong> ${meta.strategy}`;

  updateClusterCategoryChart(details.category_sales, meta.color);
  highlightScatter(clusterId);
}


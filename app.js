function renderClusterScatter() {
  const ctx = document.getElementById('clusterScatterChart').getContext('2d');
  
  const names = { 0: '로열충성', 1: '이탈위험', 2: '고단가프리미엄', 3: '체리피커(할인민감)' };
  const colors = { 0: '#06b6d4', 1: '#ef4444', 2: '#10b981', 3: '#f59e0b' };

  const datasets = [0, 2, 3, 1].map(code => {
    const pts = CLUSTER_DATA.scatter_sample
      .filter(s => s.cluster === code)
      .map(s => ({ x: s.평균할인율, y: s.총결제 / 10000 }));

    return {
      label: names[code],
      data: pts,
      backgroundColor: colors[code],
      borderColor: '#090d16',
      borderWidth: 1,
      pointRadius: 4,
      pointHoverRadius: 7
    };
  });

  clusterScatterChart = new Chart(ctx, {
    type: 'scatter',
    data: { datasets: datasets },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: {
          position: 'top',
          labels: { color: '#94a3b8', font: { size: 10 }, boxWidth: 10 }
        },
        tooltip: {
          callbacks: {
            label: ctx => ` 할인율: ${ctx.raw.x}% | 연간매출: ${ctx.raw.y.toFixed(1)}만원`
          }
        }
      },
      scales: {
        x: {
          title: { display: true, text: '고객 평균 할인율 (%)', color: '#94a3b8', font: { size: 11 } },
          grid: { color: 'rgba(255,255,255,0.04)' },
          ticks: { color: '#94a3b8' }
        },
        y: {
          title: { display: true, text: '연간 총 결제액 (만원)', color: '#94a3b8', font: { size: 11 } },
          grid: { color: 'rgba(255,255,255,0.04)' },
          ticks: { color: '#94a3b8' }
        }
      }
    }
  });
}

function highlightScatter(clusterId) {
  if (!clusterScatterChart) return;
  const clusterCodes = { 'royal': 0, 'premium': 2, 'cherrypicker': 3, 'dormant': 1 };
  const targetCode = clusterCodes[clusterId];

  clusterScatterChart.data.datasets.forEach((ds, idx) => {
    const isTarget = [0, 2, 3, 1][idx] === targetCode;
    ds.pointRadius = isTarget ? 6 : 2.5;
    ds.borderWidth = isTarget ? 2 : 0;
  });
  clusterScatterChart.update();
}

function updateClusterCategoryChart(categorySales, color) {
  const ctx = document.getElementById('clusterCategoryBarChart').getContext('2d');
  
  const sorted = Object.entries(categorySales).sort((a, b) => b[1] - a[1]);
  const labels = sorted.map(s => s[0]);
  const data = sorted.map(s => (s[1] / 10000000).toFixed(1));

  if (clusterCategoryBarChart) {
    clusterCategoryBarChart.data.labels = labels;
    clusterCategoryBarChart.data.datasets[0].data = data;
    clusterCategoryBarChart.data.datasets[0].backgroundColor = color;
    clusterCategoryBarChart.update();
  } else {
    clusterCategoryBarChart = new Chart(ctx, {
      type: 'bar',
      data: {
        labels: labels,
        datasets: [{
          label: '매출(천만원)',
          data: data,
          backgroundColor: color,
          borderRadius: 4
        }]
      },
      options: {
        responsive: true,
        maintainAspectRatio: false,
        plugins: { legend: { display: false } },
        scales: {
          x: { grid: { display: false }, ticks: { color: '#94a3b8', font: { size: 9 } } },
          y: { grid: { color: 'rgba(255,255,255,0.03)' }, ticks: { color: '#94a3b8', font: { size: 9 }, callback: v => v + '천만' } }
        }
      }
    });
  }
}
